interface ProviderCheckpointClassification {
  status: string;
  blockerKind: string;
  nextAction: string;
  evidenceKind: string;
  agentCanContinue: boolean;
}

async function classifyProviderCheckpoint(
  page: Page,
  plan: AppFactoryProviderBrowserPlan,
  error?: string,
): Promise<ProviderCheckpointClassification> {
  const title = await page.title().catch(() => "");
  const finalUrl = sanitizeProviderUrl(page.url());
  const signals = await page.evaluate(() => {
    const bodyText = document.body?.innerText || "";
    const inputs = Array.from(document.querySelectorAll("input"));
    const links = Array.from(document.querySelectorAll("a, button")).slice(0, 80).map((el) => el.textContent || "");
    return {
      bodyText: bodyText.slice(0, 6000),
      actionText: links.join(" ").slice(0, 3000),
      passwordInputs: inputs.filter((input) => input.type === "password").length,
      emailInputs: inputs.filter((input) => input.type === "email" || /email|user|login/i.test(`${input.name} ${input.id} ${input.placeholder}`)).length,
      paymentInputs: inputs.filter((input) => /card|cc|cvc|cvv|expiry|payment|billing/i.test(`${input.name} ${input.id} ${input.placeholder}`)).length,
    };
  }).catch(() => ({
    bodyText: "",
    actionText: "",
    passwordInputs: 0,
    emailInputs: 0,
    paymentInputs: 0,
  }));
  const haystack = [
    finalUrl,
    title,
    signals.bodyText,
    signals.actionText,
    error || "",
  ].join(" ").toLowerCase();

  const hasCaptcha = /captcha|cloudflare|verify you are human|human verification|unusual traffic|access denied|blocked|bot check/.test(haystack);
  const hasPayment = signals.paymentInputs > 0 || /checkout|payment|billing|card number|subscribe|pricing|결제|카드/.test(haystack);
  const hasLogin = signals.passwordInputs > 0 || /log in|login|sign in|signin|oauth|로그인|password|비밀번호/.test(haystack);
  const hasSignup = /sign up|signup|create account|register|회원가입|start free trial|get started/.test(haystack);
  const hasConsole = /api key|access token|developer|console|dashboard|project|settings|workspace|supabase|stripe|google cloud/.test(haystack);

  if (hasCaptcha) {
    return {
      status: "secure-human-checkpoint-required",
      blockerKind: "captcha-or-provider-bot-check",
      evidenceKind: "verified-provider-page",
      agentCanContinue: false,
      nextAction: "Pause in a controlled provider browser for human verification, then resume the same provider run without storing cookies, passwords, OTPs, or card data.",
    };
  }
  if (plan.type === "payment" && hasPayment) {
    return {
      status: "secure-human-checkpoint-required",
      blockerKind: "payment-checkout-approval-required",
      evidenceKind: "verified-provider-page",
      agentCanContinue: false,
      nextAction: "Collect explicit payment-scope approval, accept card/CVV only through provider checkout or tokenized Agentlas payment UI, then store approved scope and receipt metadata.",
    };
  }
  if (hasLogin) {
    return {
      status: "secure-human-checkpoint-required",
      blockerKind: "login-or-oauth-required",
      evidenceKind: "verified-provider-page",
      agentCanContinue: false,
      nextAction: "Ask for a secure provider login/signup checkpoint and resume after password, OTP, or OAuth consent is supplied through Agentlas secure input or the controlled browser.",
    };
  }
  if (hasSignup) {
    return {
      status: "secure-human-checkpoint-required",
      blockerKind: "signup-required",
      evidenceKind: "verified-provider-page",
      agentCanContinue: false,
      nextAction: "Have the agent draft the signup flow, pause for legal identity or terms acceptance, then continue once the provider account exists.",
    };
  }
  if (error) {
    return {
      status: "browser-checkpoint-or-blocked",
      blockerKind: "network-or-provider-blocked",
      evidenceKind: "verified-provider-page",
      agentCanContinue: false,
      nextAction: "Retry through a visible controlled browser, switch to the provider API path if credentials exist, or select an equivalent fallback provider.",
    };
  }
  if (hasConsole || plan.envKey) {
    return {
      status: "agent-browser-can-continue",
      blockerKind: "none",
      evidenceKind: "verified-provider-page",
      agentCanContinue: true,
      nextAction: "Continue provider setup in the browser; if an API key or project secret is generated, save only a fingerprint and put the secret in the Agentlas vault.",
    };
  }
  return {
    status: "provider-page-ready",
    blockerKind: "none",
    evidenceKind: "verified-provider-page",
    agentCanContinue: true,
    nextAction: "Continue the provider workflow from this page or fall back to the local Agentlas adapter if the provider path becomes unavailable.",
  };
}

