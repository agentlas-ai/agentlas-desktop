function updateCredentialLedgers(
  operations: JsonObject,
  credentials: AppFactoryProviderCredentialResolution[],
  now: string,
): void {
  const byConnector = new Map(credentials.filter((item) => item.connectorId).map((item) => [item.connectorId, item]));
  const ledgers = objectValue(operations.ledgers);
  const connectors = arrayOfObjects(operations.connectors);
  const statusForProvider = (provider: unknown): AppFactoryProviderCredentialResolution | undefined => {
    const raw = `${provider || ""}`.toLowerCase();
    const connector = connectors.find((item) => `${item.name || ""}`.toLowerCase() === raw || `${item.id || ""}`.toLowerCase() === raw);
    const id = stringValue(connector?.id);
    return id ? byConnector.get(id) : undefined;
  };
  ledgers.databases = arrayOfObjects(ledgers.databases).map((item) => {
    const resolved = statusForProvider(item.provider);
    if (!resolved) return item;
    return {
      ...item,
      status: resolved.status === "live-credential-ready" ? "live-credential-ready" : item.status,
      evidenceKind: resolved.status === "live-credential-ready" ? "verified-local" : item.evidenceKind,
      lastRunAt: now,
      ...(resolved.fingerprint ? { credentialFingerprint: resolved.fingerprint } : {}),
    };
  }) as unknown as JsonValue;
  ledgers.imageGeneration = arrayOfObjects(ledgers.imageGeneration).map((item) => {
    const resolved = statusForProvider(item.provider);
    if (!resolved) return item;
    return {
      ...item,
      credentialStatus: resolved.status,
      lastRunAt: now,
      ...(resolved.fingerprint ? { credentialFingerprint: resolved.fingerprint } : {}),
    };
  }) as unknown as JsonValue;
  ledgers.payments = arrayOfObjects(ledgers.payments).map((item) => {
    const resolved = statusForProvider(item.provider);
    if (!resolved) return item;
    return {
      ...item,
      credentialStatus: resolved.status,
      lastRunAt: now,
      ...(resolved.fingerprint ? { credentialFingerprint: resolved.fingerprint } : {}),
    };
  }) as unknown as JsonValue;
  operations.ledgers = ledgers as unknown as JsonValue;
}

