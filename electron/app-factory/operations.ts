function sanitizeProviderBrowserResult(raw: JsonObject, session: JsonObject): JsonObject {
  const connectorId = safeProviderResultText(raw.connectorId, 120) || stringValue(session.connectorId) || "provider";
  const connectorName = safeProviderResultText(raw.connectorName, 160) || stringValue(session.connectorName) || connectorId;
  const status = safeProviderResultText(raw.status, 120) || "unknown";
  const safeStorage = Array.isArray(raw.safeStorage)
    ? raw.safeStorage.map((item) => safeProviderResultText(item, 180)).filter((item): item is string => Boolean(item)).slice(0, 8)
    : [
      "sanitized metadata only",
      "never password, OTP, raw card, CVV/CVC, cookies, tokens, or provider session secrets",
    ];
  return {
    version: safeProviderResultText(raw.version, 20) || "0.1",
    kind: "provider-browser-session-result",
    connectorId,
    connectorName,
    type: safeProviderResultText(raw.type, 120) || stringValue(session.type) || "provider",
    status,
    ...(safeProviderUrl(raw.finalUrl) ? { finalUrl: safeProviderUrl(raw.finalUrl) } : {}),
    ...(safeProviderResultText(raw.title, 240) ? { title: safeProviderResultText(raw.title, 240) } : {}),
    ...(safeProviderResultText(raw.error, 400) ? { error: safeProviderResultText(raw.error, 400) } : {}),
    ...(safeProviderResultText(raw.updatedAt, 80) ? { updatedAt: safeProviderResultText(raw.updatedAt, 80) } : {}),
    ...(safeProviderResultText(raw.closedAt, 80) ? { closedAt: safeProviderResultText(raw.closedAt, 80) } : {}),
    ...(safeProviderResultText(raw.capturedAt, 80) ? { capturedAt: safeProviderResultText(raw.capturedAt, 80) } : {}),
    safeStorage,
  };
}

function safeProviderUrl(value: unknown): string | undefined {
  const raw = safeProviderResultText(value, 500);
  if (!raw) return undefined;
  try {
    const parsed = new URL(raw);
    if (parsed.search) parsed.search = "?redacted=1";
    if (parsed.hash) parsed.hash = "#redacted";
    return parsed.toString();
  } catch {
    return raw;
  }
}

function safeProviderResultText(value: unknown, maxLength: number): string | undefined {
  const raw = stringValue(value)?.trim();
  if (!raw) return undefined;
  const redacted = raw
    .replace(/\b(?:\d[ -]?){13,19}\b/g, "[redacted-number]")
    .replace(/\b(password|passwd|token|secret|api[_-]?key|otp|cvv|cvc)\s*[:=]\s*[^\s&]+/gi, "$1=[redacted]");
  return redacted.slice(0, maxLength);
}

function providerResultAgentCanContinue(status: string, error?: string): boolean {
  if (error) return false;
  const normalized = status.toLowerCase().trim();
  if (!normalized || normalized.includes("error") || normalized === "interrupted" || normalized === "terminated") {
    return false;
  }
  return [
    "closed",
    "closed-after-user-checkpoint",
    "completed",
    "complete",
    "ready",
    "provider-ready",
    "credentials-configured",
    "signup-complete",
    "checkout-approved",
  ].includes(normalized);
}

