const LOCAL_ASSET_GENERATOR = "agentlas-local-catalog-asset-generator";

export async function installMcpPlan(
  input: AppFactoryRootRequest,
): Promise<AppFactoryMcpInstallResult> {
  const rootPath = await assertAppRoot(input.rootPath);
  const pkg = await readAppPackage(rootPath);
  const now = new Date().toISOString();
  const adapters = pkg.connectors.map((connector) => {
    const id = slugify(connector.id || connector.name);
    const envKey = credentialEnvKey(connector);
    return {
      id,
      name: connector.name,
      type: connector.type,
      path: `mcp/servers/${id}.mjs`,
      envKey,
      status: connector.status || "proposed",
      connector,
    };
  });

  for (const adapter of adapters) {
    const abs = path.join(rootPath, adapter.path);
    assertInside(rootPath, abs);
    await fs.mkdir(path.dirname(abs), { recursive: true });
    await fs.writeFile(abs, mcpAdapterStub(adapter), "utf8");
  }

  const mcpConfig = {
    mcpServers: Object.fromEntries(
      adapters.map((adapter) => [
        adapter.id,
        {
          command: "node",
          args: [adapter.path],
          env: adapter.envKey ? { [adapter.envKey]: `<${adapter.envKey}>` } : {},
        },
      ]),
    ),
  };
  const envExample = adapters
    .filter((adapter) => adapter.envKey)
    .map((adapter) => `${adapter.envKey}=`)
    .join("\n");
  const mcpInstallDoc = [
    `# ${appName(pkg)} MCP Install Plan`,
    "",
    "Generated by Agentlas App Factory.",
    "",
    "## What Was Created",
    "",
    "- `.mcp.json` for local adapter wiring",
    "- `mcp/servers/*.mjs` adapter stubs",
    "- `.env.example` credential placeholders",
    "",
    "## Credential Gate",
    "",
    "Adapters do not call external services until credentials are saved through Agentlas.",
    "",
    ...adapters.map((adapter) =>
      [
        `### ${adapter.name}`,
        "",
        `- Adapter: \`${adapter.path}\``,
        `- Type: \`${adapter.type}\``,
        adapter.envKey ? `- Required key: \`${adapter.envKey}\`` : "- Required key: none declared",
        adapter.envKey
          ? `- Save: \`agentlas creds save --provider ${adapter.id} --key ${adapter.envKey} --value <value> --project .\``
          : "",
        "",
      ].join("\n"),
    ),
  ].join("\n");

  const configPath = path.join(rootPath, ".mcp.json");
  const envPath = path.join(rootPath, ".env.example");
  const installDocPath = path.join(rootPath, "mcp", "INSTALL.md");
  await fs.writeFile(configPath, `${JSON.stringify(mcpConfig, null, 2)}\n`, "utf8");
  await fs.writeFile(envPath, envExample ? `${envExample}\n` : "# No credentials declared yet.\n", "utf8");
  await fs.writeFile(installDocPath, mcpInstallDoc, "utf8");

  return {
    rootPath,
    configPath,
    envPath,
    adapters: adapters.map(({ connector: _connector, ...adapter }) => adapter),
    missingCredentials: adapters.flatMap((adapter) => (adapter.envKey ? [adapter.envKey] : [])),
    createdAt: now,
  };
}

