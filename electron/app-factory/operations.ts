  if (type === "database") return ["Supabase", "Neon Postgres", "SQLite local-first stack", "Firebase"];
  if (type === "model") return ["OpenAI Images", "Adobe Firefly", "Higgsfield", "local SVG asset generator"];
  if (type === "api" || type === "oauth") return ["Vercel", "Netlify", "Cloudflare Pages", "Agentlas local preview"];
