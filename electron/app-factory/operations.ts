function sanitizeProviderEvidence(value: string): string {
  return value
    .replace(/([?&](?:token|access_token|refresh_token|code|key|secret|password|session|auth|signature)=)[^&\s]+/gi, "$1redacted")
    .replace(/\b(?:sk|pk)_(?:live|test)_[A-Za-z0-9_]{8,}\b/g, "[redacted-key]")
    .slice(0, 500);
}

