export async function runAppFactoryAutopilot(
  input: AppFactoryAutopilotRequest,
): Promise<AppFactoryAutopilotResult> {
  const rootPath = await assertAppRoot(input.rootPath);
  const pkg = await readAppPackage(rootPath);
  const createdAt = new Date().toISOString();
  const operationsPath = path.join(rootPath, "data", "operations.json");
  const operations = await readOperations(operationsPath);
  const domain = stringValue(pkg.manifest.domain) || "general";
  const steps: AppFactoryAutopilotStep[] = [];
  const waitingOn = new Set<string>();
  const result: AppFactoryAutopilotResult = {
    rootPath,
    appName: appName(pkg),
    domain,
    status: "needs-review",
    steps,
    waitingOn: [],
    createdAt,
    summary: "Agentlas OS autopilot has not started.",
  };

  const completeStep = (id: string, label: string, summary: string): void => {
    steps.push({ id, label, status: "completed", summary });
  };
  const skipStep = (id: string, label: string, summary: string): void => {
    steps.push({ id, label, status: "skipped", summary });
  };
  const waitStep = (id: string, label: string, summary: string, waitKey: string): void => {
    waitingOn.add(waitKey);
    steps.push({ id, label, status: "waiting", summary });
  };
  const failStep = (id: string, label: string, err: unknown): void => {
    steps.push({ id, label, status: "failed", summary: errorSummary(err) });
  };

  try {
    result.providerRun = await runProviderTasks({ rootPath });
    completeStep("provider-tasks", "Advance provider tasks", result.providerRun.summary);
    if (result.providerRun.secureInputRequiredCount > 0) {
      waitingOn.add("secure-provider-input");
    }
  } catch (err) {
    failStep("provider-tasks", "Advance provider tasks", err);
  }

  try {
    result.providerBrowser = await prepareProviderBrowserOpen({ rootPath });
    completeStep("provider-browser", "Prepare provider browser delegation", result.providerBrowser.summary);
  } catch (err) {
    failStep("provider-browser", "Prepare provider browser delegation", err);
  }

  try {
    result.providerBrowserSessions = await captureProviderBrowserSessions({
      rootPath,
      mode: input.browserMode || (input.captureProviderSessions ? "headless" : "plan-only"),
      timeoutMs: input.timeoutMs ?? (input.captureProviderSessions ? 12_000 : undefined),
      screenshot: input.captureProviderSessions ? true : false,
    });
    completeStep("provider-browser-sessions", "Capture provider checkpoints", result.providerBrowserSessions.summary);
  } catch (err) {
    waitStep("provider-browser-sessions", "Capture provider checkpoints", errorSummary(err), "provider-browser-checkpoint");
  }

  try {
    result.credentialResolution = await resolveProviderCredentials({
      rootPath,
      source: input.credentialSource || "agentlas-env-vault",
    });
    if (result.credentialResolution.missingCount > 0) {
      waitStep(
        "credentials",
        "Resolve provider credentials",
        result.credentialResolution.summary,
        "credential-vault-input",
      );
    } else {
      completeStep("credentials", "Resolve provider credentials", result.credentialResolution.summary);
    }
  } catch (err) {
    waitStep("credentials", "Resolve provider credentials", errorSummary(err), "credential-vault-input");
  }

  const collections = objectValue(operations.collections);
  const products = arrayOfObjects(collections.products);
  if (domain === "ecommerce" && products.length > 0) {
    try {
      result.materializedAssets = await materializeCatalogAssets({
        rootPath,
        budgetApproved: input.budgetApproved === true,
        approvedBy: input.approvedBy || "agentlas-os-autopilot",
        approvalReason: input.approvalReason || "Agentlas OS autopilot catalog asset materialization",
      });
      completeStep("materialize-assets", "Materialize catalog assets", result.materializedAssets.summary);
    } catch (err) {
      waitStep("materialize-assets", "Materialize catalog assets", errorSummary(err), "generation-budget-approval");
    }

    try {
      result.localStack = await activateLocalCommerceStack({
        rootPath,
        mode: "local-first",
        activatedBy: input.approvedBy || "agentlas-os-autopilot",
      });
      completeStep("local-commerce", "Activate local commerce stack", result.localStack.summary);
    } catch (err) {
      failStep("local-commerce", "Activate local commerce stack", err);
    }
  } else {
    skipStep("local-commerce", "Activate local commerce stack", "No ecommerce product collection was declared.");
  }

  try {
    result.mcp = await installMcpPlan({ rootPath });
    completeStep("mcp", "Prepare MCP adapters", `${result.mcp.adapters.length} MCP adapter(s) prepared.`);
  } catch (err) {
    failStep("mcp", "Prepare MCP adapters", err);
  }

  try {
    result.smoke = await runAppFactorySmoke({ rootPath });
    if (result.smoke.ok) {
      completeStep("smoke", "Run smoke test", "Smoke test passed.");
    } else {
      failStep("smoke", "Run smoke test", `Smoke exited ${result.smoke.exitCode ?? "unknown"}.`);
    }
  } catch (err) {
    failStep("smoke", "Run smoke test", err);
  }

  if (result.smoke?.ok) {
    try {
      result.preview = await preparePreviewDeploy({ rootPath });
      completeStep("preview", "Package preview", `Preview package ready at ${result.preview.deployPath}.`);
    } catch (err) {
      failStep("preview", "Package preview", err);
    }

    try {
      result.appTool = await publishAppAsTool({ rootPath });
      completeStep("publish-tool", "Publish app as reusable tool", result.appTool.summary);
    } catch (err) {
      failStep("publish-tool", "Publish app as reusable tool", err);
    }
  } else {
    skipStep("preview", "Package preview", "Skipped until smoke test passes.");
    skipStep("publish-tool", "Publish app as reusable tool", "Skipped until smoke test passes.");
  }

  const failedCount = steps.filter((step) => step.status === "failed").length;
  const completedCount = steps.filter((step) => step.status === "completed").length;
  if (
    (result.credentialResolution && result.credentialResolution.missingCount === 0) ||
    result.localStack?.products
  ) {
    waitingOn.delete("secure-provider-input");
  }
  result.waitingOn = [...waitingOn];
  result.status = result.smoke?.ok && result.appTool ? "operated" : result.waitingOn.length > 0 ? "waiting-for-secure-input" : "needs-review";
  result.summary =
    result.status === "operated"
      ? `Agentlas OS operated ${completedCount} step(s), produced a preview, and published the app as a reusable tool.`
      : `Agentlas OS completed ${completedCount} step(s), ${failedCount} failed, ${result.waitingOn.length} waiting on secure input.`;

  const finalOperations = await readOperations(operationsPath);
  const finalCollections = objectValue(finalOperations.collections);
  const events = Array.isArray(finalCollections.events) ? finalCollections.events.filter(isObject) : [];
  events.push({
    at: createdAt,
    actor: "agentlas-os-autopilot",
    type: "autopilot-run",
    summary: result.summary,
  });
  finalCollections.events = events as unknown as JsonValue;
  finalOperations.collections = finalCollections as unknown as JsonValue;
  finalOperations.autopilot = {
    status: result.status,
    ranAt: createdAt,
    steps,
    waitingOn: result.waitingOn,
    summary: result.summary,
    safeBoundaries: [
      "no raw passwords, OTPs, cards, CVV, cookies, or tokens are written to chat/files/logs",
      "paid checkout requires explicit approval with merchant, amount, currency, recurrence, and purpose",
      "missing API/MCP becomes browser delegation or local fallback, not a dead end",
      "sudo-like destructive deletion is outside autopilot scope",
    ],
  } as unknown as JsonValue;
  await writeOperationsFiles(rootPath, finalOperations, arrayOfObjects(finalOperations.providerTasks));
  await refreshServiceAppViews(rootPath, createdAt);

  return result;
}

