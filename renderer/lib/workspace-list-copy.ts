export const listCopy = (locale: ListLocale) => COPY[locale === "ko" ? "ko" : "en"];

/**
 * What a rejected call of this screen shows. None of the calls the list makes (home.tree / rowsByIds / participants / openMember,
 * chats.createAgentChat / remove / rename) answers with a machine refusal code: Main throws one sentence, already in the app's language
 * (electron/one/agent-chat.ts, electron/chat/*), and that sentence is shown as it is. A bare transport / validation message
 * ("Invalid ...", "Error invoking ...") or an empty one is replaced by the general line - no new sentence per cause is invented here.
 */
export function listFailureText(cause: unknown, locale: ListLocale): string {
  const raw = cause instanceof Error ? cause.message : typeof cause === "string" ? cause : "";
  const text = raw.replace(/^Error invoking remote method '[^']+': (?:Error: |TypeError: )?/, "").trim();
  if (!text || /^(invalid |typeerror|error invoking)/i.test(text) || text.length > 240) return listCopy(locale).failedGeneric;
  return text;
}
