/** The drag payload the left list carries. */
export const CHAT_DRAG_MIME = "application/x-agentlas-chat";
export interface ChatDragPayload { chatId: string; kind: "room" | "work"; groupKey?: string; fromTab?: boolean }
export function readChatDrag(event: { dataTransfer: DataTransfer | null }): ChatDragPayload | null {
  try {
    const raw = event.dataTransfer?.getData(CHAT_DRAG_MIME);
    if (!raw) return null;
    const value = JSON.parse(raw) as Partial<ChatDragPayload>;
    return typeof value.chatId === "string" && value.chatId ? { chatId: value.chatId, kind: value.kind === "work" ? "work" : "room", groupKey: typeof value.groupKey === "string" ? value.groupKey : undefined, fromTab: value.fromTab === true } : null;
  } catch { return null; }
}
export const hasChatDrag = (event: { dataTransfer: DataTransfer | null }): boolean => Array.from(event.dataTransfer?.types ?? []).includes(CHAT_DRAG_MIME);

