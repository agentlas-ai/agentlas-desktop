  // Korean particles that attach directly to the noun in front of them. Do NOT remove this guard.
  // The noun-level fallback below is a partial substitution: without the guard, a sentence with no
  // entry of its own -- "아직 연구 계약이 없습니다." -- comes out as "아직 Research contract이
  // 없습니다.", an English noun welded to a Korean particle. That is worse than leaving the
  // sentence in Korean, and worse in a specific way: a half-translated sentence looks translated,
  // so the missing entry becomes invisible to everyone reading the screen. A fully Korean sentence
  // is honest and keeps the gap visible until someone writes the sentence entry.
  const TRAILING_PARTICLE = /^(?:으로|부터|까지|이|가|은|는|을|를|로|의|에|와|과|도|만)/;

  // Replace every occurrence of `source` except the ones a Korean particle is glued onto.
  function replaceOutsideParticles(input, source, target) {
    let output = "";
    let index = 0;
    for (;;) {
      const at = input.indexOf(source, index);
      if (at === -1) return output + input.slice(index);
      const after = input.slice(at + source.length);
      output += input.slice(index, at) + (TRAILING_PARTICLE.test(after) ? source : target);
      index = at + source.length;
    }
  }

  function translateText(value) {
    const input = String(value ?? "");
    if (locale === "ko" || !HANGUL.test(input)) return input;
    const leading = input.match(/^\s*/)?.[0] || "";
    const trailing = input.match(/\s*$/)?.[0] || "";
    const core = input.slice(leading.length, input.length - trailing.length || undefined);
    // A full-sentence entry always wins. Exact copy is returned before any pattern or partial
    // substitution runs, so an added sentence is never re-cut by the noun-level fallback below.
    const exact = ENGLISH_COPY.get(core);
    if (exact !== undefined) {
      return `${leading}${exact}${trailing}`;
    }
    let output = core;
    for (const [pattern, replacement] of ENGLISH_PATTERNS) {
      if (pattern.test(output)) output = output.replace(pattern, replacement);
    }
    // Noun-level substitution is deliberately OFF.
    //
    // It used to swap known nouns inside any sentence that had no exact entry, which produced
    // half-English text: `아직 연구 계약이 없습니다.` came out as `아직 Research contract이 없습니다.`
    // -- an English noun welded to a Korean particle, readable in neither language. Worse, a
    // half-translated sentence LOOKS translated, so the missing entry stops being visible to the
    // next person who reads the English UI.
    //
    // Switching it off was measured, not assumed: of 324 whole runtime sentences, exactly two
    // depended on it, and both now have their own entries. Whole Korean beats broken bilingual,
    // and it shows where the gap is.
    //
    // `replaceOutsideParticles` is kept below rather than deleted: if anyone turns this back on,
    // the particle problem returns with it and that helper is the guard against it.
    if (HANGUL.test(output)) untranslated.add(core);
    return `${leading}${output}${trailing}`;
  }

