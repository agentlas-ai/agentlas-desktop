#!/usr/bin/env node
"use strict";
// Generates shared/app-screen-routes.generated.ts: the URL path of every screen the renderer can show, read from the Next app
// directory (renderer/app/**/page.tsx; a route group such as (shell) is not part of the URL). app.navigate answers from this
// list, so a path that is not a screen is refused instead of reported as "opened" (the renderer treats any well-formed path as
// applied, and Next answers an unknown one with its not-found page).
//   node scripts/generate-app-screen-routes.cjs          write the file
//   node scripts/generate-app-screen-routes.cjs --check  exit 1 when the file is stale (build:electron runs this)
const fs = require("node:fs");
const path = require("node:path");

const repo = path.resolve(__dirname, "..");
const appDir = path.join(repo, "renderer", "app");
const output = path.join(repo, "shared", "app-screen-routes.generated.ts");
const check = process.argv.includes("--check");
const PAGE = /^page\.(?:tsx|ts|jsx|js|mdx)$/;
// Git may check this repository out with CRLF on Windows; the generated file must not look stale for that.
const normalize = (text) => text.replace(/\r\n?/g, "\n");

const pages = new Set();
(function walk(directory, segments) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
    if (entry.isDirectory()) {
      const name = entry.name;
      if (name.startsWith("_") || name.startsWith("@")) continue; // private folders and parallel slots are not URLs
      if (/^\(.+\)$/.test(name)) { walk(path.join(directory, name), segments); continue; } // route group
      if (name.startsWith("[")) {
        throw new Error(`${path.relative(repo, path.join(directory, name))}: a dynamic route segment is not supported here. List the screens it serves explicitly or extend this generator and shared/app-screen-routes.ts together.`);
      }
      walk(path.join(directory, name), [...segments, name]);
    } else if (PAGE.test(entry.name)) {
      pages.add(`/${segments.join("/")}`);
    }
  }
})(appDir, []);

const list = [...pages].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
if (!list.length) throw new Error("no renderer page found under renderer/app");
const expected = `// Generated by scripts/generate-app-screen-routes.cjs from renderer/app/**/page.tsx. Do not edit.
// Regenerate after adding or removing a renderer page: node scripts/generate-app-screen-routes.cjs
export const APP_SCREEN_PAGES: readonly string[] = [
${list.map((route) => `  ${JSON.stringify(route)},`).join("\n")}
];
`;

if (check) {
  const actual = fs.existsSync(output) ? normalize(fs.readFileSync(output, "utf8")) : null;
  if (actual !== expected) {
    console.error(`app screen routes are stale: ${path.relative(repo, output)} does not list the pages under renderer/app.\n  regenerate: node scripts/generate-app-screen-routes.cjs`);
    process.exit(1);
  }
} else {
  fs.writeFileSync(output, expected);
}
console.log(`app screen routes ${check ? "verified" : "generated"}: ${list.length} pages`);
